// Writes src/app/core/env.generated.ts from environment variables (or a local .env file).
// Runs automatically before `npm start` and `npm run build`.
// Only PUBLIC values go here — they end up in the browser bundle.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

if (existsSync('.env')) {
  for (const line of readFileSync('.env', 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const env = {
  supabaseUrl: process.env.SUPABASE_URL ?? '',
  supabaseAnonKey: process.env.SUPABASE_ANON_KEY ?? '',
  siteUrl: (process.env.SITE_URL ?? '').replace(/\/$/, ''),
};

writeFileSync(
  'src/app/core/env.generated.ts',
  `// Generated by scripts/write-env.mjs — do not edit, do not commit.\nexport const GENERATED_ENV: { supabaseUrl: string; supabaseAnonKey: string; siteUrl: string } = ${JSON.stringify(env, null, 2)};\n`,
);
console.log(`env: ${env.supabaseUrl ? 'Supabase configured' : 'no Supabase → demo mode'}${env.siteUrl ? `, site ${env.siteUrl}` : ''}`);
