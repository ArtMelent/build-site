// Writes src/app/core/env.generated.ts from environment variables (or a local .env file).
// Runs automatically before `npm start` and `npm run build`. Only public values go here.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

if (existsSync('.env')) {
  for (const line of readFileSync('.env', 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const env = { siteUrl: (process.env.SITE_URL ?? '').replace(/\/$/, '') };

writeFileSync(
  'src/app/core/env.generated.ts',
  `// Generated by scripts/write-env.mjs — do not edit, do not commit.\nexport const GENERATED_ENV: { siteUrl: string } = ${JSON.stringify(env, null, 2)};\n`,
);
console.log(`env: ${env.siteUrl ? `site ${env.siteUrl}` : 'SITE_URL not set (canonical links will be relative)'}`);
