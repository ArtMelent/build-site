// Generates supabase/seed.sql from src/app/core/data/seed-services.json,
// so the built-in demo data and the database start from the same content.
// Usage: node scripts/gen-seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const services = JSON.parse(readFileSync('src/app/core/data/seed-services.json', 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const rows = services.map((s) =>
  `  (${[q(s.slug), q(s.title), q(s.short_description), q(s.intro), q(s.body), arr(s.highlights),
       s.price_from ?? 'null', q(s.price_unit), q(s.image_url), q(s.seo_title), q(s.seo_description),
       s.sort_order, s.is_published].join(',\n   ')})`
).join(',\n');

const sql = `-- Initial services. Generated by scripts/gen-seed-sql.mjs — do not edit by hand.
-- Safe to run more than once: existing slugs are left untouched.
insert into public.services
  (slug, title, short_description, intro, body, highlights,
   price_from, price_unit, image_url, seo_title, seo_description, sort_order, is_published)
values
${rows}
on conflict (slug) do nothing;
`;
writeFileSync('supabase/seed.sql', sql);
console.log(`supabase/seed.sql: ${services.length} services`);
